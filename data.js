/* 한 판은 10문제. 쉬운 것만 나오거나 어려운 것만 나오면 둘 다 재미가 없어서,
   난이도별로 뽑은 뒤 섞는다. 문항이 모자라면 있는 만큼만 낸다. */
export const ROUND_SIZE = 10;
const MIX = { easy: 3, mid: 4, hard: 3 };

function shuffle(list, rand) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** 한 판에 낼 문제 10개를 만든다. 보기는 문항마다 섞어서 정답 자리가 고정되지 않게 한다.
 *
 * 같은 작품은 한 판에 한 번만 낸다. 햄릿처럼 난이도 세 칸에 문항이 흩어진 작품은
 * 그냥 뽑으면 한 판에 세 번까지 나와, 같은 답을 세 번 고르는 판이 된다.
 * 문항이 모자라면 그때만 중복을 허용한다 — 짧은 판을 내보내는 것보다 낫다.
 */
export function buildRound(rand = Math.random) {
  const picked = [];
  const usedWorks = new Set();

  const take = (pool, count, allowSameWork) => {
    for (const q of pool) {
      if (count <= 0) break;
      if (picked.includes(q)) continue;
      if (!allowSameWork && usedWorks.has(q.work)) continue;
      picked.push(q);
      usedWorks.add(q.work);
      count -= 1;
    }
    return count; // 못 채운 만큼
  };

  for (const [level, count] of Object.entries(MIX)) {
    const pool = shuffle(QUESTIONS.filter((q) => q.level === level), rand);
    const short = take(pool, count, false);
    if (short > 0) take(pool, short, true); // 그 난이도가 동나면 작품 중복을 허용해 채운다
  }

  // 난이도 배분으로도 모자랐으면 난이도를 가리지 않고 채운다.
  if (picked.length < ROUND_SIZE) {
    const rest = shuffle(QUESTIONS, rand);
    const short = take(rest, ROUND_SIZE - picked.length, false);
    if (short > 0) take(rest, short, true);
  }

  return shuffle(picked, rand)
    .slice(0, ROUND_SIZE)
    .map((q) => ({ ...q, choices: shuffle([q.work, ...q.decoys], rand) }));
}
