/* 기본 한 판은 10문제. 쉬운 것만 나오거나 어려운 것만 나오면 둘 다 재미가 없어서,
   판 길이에 맞춰 난이도별로 뽑은 뒤 섞는다. 문항이 모자라면 있는 만큼만 낸다. */
export const ROUND_SIZE = 10;
const MIX = { easy: 0.3, mid: 0.4, hard: 0.3 };

function shuffle(list, rand) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/* 비율별 몫을 내림한 뒤 소수 부분이 큰 순서로 남은 자리를 하나씩 준다.
   그래서 모든 크기에서 난이도별 개수의 합이 정확히 판 크기와 같다. */
function mixFor(size) {
  const portions = Object.entries(MIX).map(([level, ratio], order) => {
    const exact = size * ratio;
    return { level, count: Math.floor(exact), fraction: exact % 1, order };
  });
  const left = size - portions.reduce((sum, part) => sum + part.count, 0);

  const byRemainder = portions.slice()
    .sort((a, b) => b.fraction - a.fraction || a.order - b.order);
  for (let i = 0; i < left; i += 1) byRemainder[i].count += 1;

  return Object.fromEntries(portions.map(({ level, count }) => [level, count]));
}

/** 한 판에 낼 문제를 만든다. 보기는 문항마다 섞어서 정답 자리가 고정되지 않게 한다.
 *
 * 같은 작품은 한 판에 한 번만 낸다. 햄릿처럼 난이도 세 칸에 문항이 흩어진 작품은
 * 그냥 뽑으면 한 판에 세 번까지 나와, 같은 답을 세 번 고르는 판이 된다.
 * 문항이 모자라면 그때만 중복을 허용한다 — 짧은 판을 내보내는 것보다 낫다.
 */
export function buildRound(size = ROUND_SIZE, rand = Math.random) {
  const picked = [];
  const usedWorks = new Set();

  const take = (pool, count, allowSameWork) => {
    for (const q of pool) {
      if (count <= 0) break;
      if (picked.includes(q)) continue;
      if (!allowSameWork && usedWorks.has(q.work)) continue;
      picked.push(q);
      usedWorks.add(q.work);
      count -= 1;
    }
    return count; // 못 채운 만큼
  };

  for (const [level, count] of Object.entries(mixFor(size))) {
    const pool = shuffle(QUESTIONS.filter((q) => q.level === level), rand);
    take(pool, count, false);
  }

  // 난이도 배분으로도 모자랐으면 난이도를 가리지 않고 채운다.
  if (picked.length < size) {
    const rest = shuffle(QUESTIONS, rand);
    const short = take(rest, size - picked.length, false);
    if (short > 0) take(rest, short, true);
  }

  return shuffle(picked, rand)
    .slice(0, size)
    .map((q) => ({ ...q, choices: shuffle([q.work, ...q.decoys], rand) }));
}
